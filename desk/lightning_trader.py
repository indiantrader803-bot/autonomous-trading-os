    async def buy_dip(self, mint: str, amount_sol: float = 0.01, slippage: int = 10, priority_fee: float = 0.0005) -> Dict[str, Any]:
        """
        Executes an instant Buy via PumpPortal Lightning API when a token passes the 8-layer check
        and pulls back by 15% (Dip Entry Rule).
        """
        url = f"{self.BASE_URL}?api-key={self.api_key}"
        payload = {
            "action": "buy",
            "mint": mint,
            "amount": amount_sol,
            "denominatedInSol": "true",
            "slippage": slippage,
            "priorityFee": priority_fee,
            "pool": "pump",
            "skipPreflight": "true"
        }

        async with httpx.AsyncClient(timeout=15.0) as client:
            try:
                res = await client.post(url, json=payload)
                data = res.json()
                logger.info(f"Lightning Buy Result for {mint}: {data}")
                return data
            except Exception as e:
                logger.error(f"Error executing Lightning buy for {mint}: {e}")
                return {"status": "error", "message": str(e)}

    async def take_profit_or_stop(self, mint: str, amount_pct: str = "100%", slippage: int = 10, priority_fee: float = 0.0005) -> Dict[str, Any]:
        """
        Executes an instant Sell (Take Profit 50% or Stop Loss 100%) via Lightning API.
        amount_pct can be "50%" or "100%".
        """
        url = f"{self.BASE_URL}?api-key={self.api_key}"
        payload = {
            "action": "sell",
            "mint": mint,
            "amount": amount_pct,
            "denominatedInSol": "false",
            "slippage": slippage,
            "priorityFee": priority_fee,
            "pool": "pump",
            "skipPreflight": "true"
        }

        async with httpx.AsyncClient(timeout=15.0) as client:
            try:
                res = await client.post(url, json=payload)
                data = res.json()
                logger.info(f"Lightning Sell Result for {mint}: {data}")
                return data
            except Exception as e:
                logger.error(f"Error executing Lightning sell for {mint}: {e}")
                return {"status": "error", "message": str(e)}
